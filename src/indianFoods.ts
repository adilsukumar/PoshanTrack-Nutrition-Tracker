export type CatalogFood = Seed;

// Preserve established entries where a named regional dish already exists.
const existingNames = new Set(INDIAN_FOODS.map(food => food.name.toLowerCase()));
for (const food of [...EXPANDED_FOODS, ...USDA_FOODS]) {
  if (!existingNames.has(food.name.toLowerCase())) {
    INDIAN_FOODS.push(food);
    existingNames.add(food.name.toLowerCase());
  }
}

const normalizeSearch = (text: string) => text.toLowerCase().normalize('NFKD').replace(/[\u0300-\u036f]/g, '').replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
const searchIndex = INDIAN_FOODS.map(item => ({ item,
  text: normalizeSearch([item.name, item.regionalName, item.region, ...(item.aliases ?? [])].filter(Boolean).join(' ')),
}));
export function searchFoods(query: string, limit = 30, region = '') {
  const tokens = normalizeSearch(query).split(' ').filter(Boolean);
  // Index once, preserve Indian entries first, and render only the requested page.
  return searchIndex.filter(({ item, text }) => (!region || item.region === region) && tokens.every(token => text.includes(token)))
    .slice(0, limit).map(({ item }) => item);
}

export function seedToFoodItem(seed: Seed): FoodItem {
  return {
    id: `${Date.now()}-${Math.random().toString(36).slice(2)}`,
    name: seed.name,
    regionalName: seed.regionalName,
    portion: seed.portion,
    calories: seed.calories,
    proteinG: seed.proteinG,
    carbsG: seed.carbsG,
    fatG: seed.fatG,
    fibreG: seed.fibreG,
    quantity: 1,
    confidence: seed.dataSource ? 'medium' : seed.notes ? 'low' : 'medium',
    notes: seed.notes ?? `Typical ${seed.region} serving; adjust for recipe and oil.`,
  };
}
